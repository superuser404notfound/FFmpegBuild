/// Proves the matroska skip_attachments patch (build.sh `patch_ffmpeg_matroska_skip_attachments`,
/// patches/matroska-skip-attachments.patch) is in the shipped libavformat.
///
/// Matroska attachments, in practice the fonts of ASS subtitles, are read in full while the
/// file opens (AetherEngine issue 956: 23 MB of fonts, about 11 s to open over a WAN address).
/// With `skip_attachments` the open passes over them and creates no attachment streams; the
/// tracks before them and their packets are unchanged.
///
/// Both fixtures carry one h264 stream and one ASS stream. `frontLayout` is mkvmerge's
/// layout, two font attachments before the first Cluster (6.5 KB). `seekHeadLayout` has one
/// 6 KB font appended behind the Clusters by mkvpropedit, so the open only reaches it through
/// the SeekHead (12.6 KB). Regenerate with:
///
///     ffmpeg -f lavfi -i color=c=black:s=16x16:r=1:d=1 -c:v libx264 -preset ultrafast -crf 51 \
///       -pix_fmt yuv420p -bsf:v filter_units=remove_types=6 v.mkv
///     printf '1\n00:00:00,000 --> 00:00:01,000\nline\n' > s.srt && ffmpeg -i s.srt s.ass
///     printf 'AE956-FONT-A' > a.ttf && printf 'AE956-FONT-B-OTF' > b.otf
///     python3 -c "open('c.ttf','wb').write(b'AE956-FONT-C'+bytes(range(256))*24)"
///     mkvmerge --no-date --disable-track-statistics-tags -o front.mkv v.mkv s.ass \
///       --attachment-mime-type font/ttf --attach-file a.ttf \
///       --attachment-mime-type font/otf --attach-file b.otf
///     mkvmerge --no-date --disable-track-statistics-tags -o seekhead.mkv v.mkv s.ass
///     mkvpropedit seekhead.mkv --attachment-mime-type font/ttf --add-attachment c.ttf
struct MatroskaSkipAttachmentsTests {

    private struct Opened {
        var codecTypes: [AVMediaType]
        var packets: Int
    }

    private static func open(_ base64: String, skip: Bool) throws -> Opened {
        let data = try #require(Data(base64Encoded: base64, options: .ignoreUnknownCharacters))
        let path = FileManager.default.temporaryDirectory
            .appendingPathComponent("mkv-skip-attachments-\(UUID().uuidString).mkv").path
        try data.write(to: URL(fileURLWithPath: path))
        defer { try? FileManager.default.removeItem(atPath: path) }

        var options: OpaquePointer?
        if skip { av_dict_set(&options, "skip_attachments", "1", 0) }
        defer { av_dict_free(&options) }
        var ctxIn: UnsafeMutablePointer<AVFormatContext>?
        try #require(avformat_open_input(&ctxIn, path, nil, &options) == 0)
        let ctx = try #require(ctxIn)
        defer { avformat_close_input(&ctxIn) }
        #expect(av_dict_count(options) == 0, "the matroska demuxer consumed the option")

        let types = (0..<Int(ctx.pointee.nb_streams)).map {
            ctx.pointee.streams[$0]!.pointee.codecpar.pointee.codec_type
        }
        var packet = av_packet_alloc()
        defer { av_packet_free(&packet) }
        var packets = 0
        while av_read_frame(ctx, packet) >= 0 {
            packets += 1
            av_packet_unref(packet)
        }
        return Opened(codecTypes: types, packets: packets)
    }

    @Test("attachments before the first Cluster are skipped, the tracks stay", arguments: [false, true])
    func frontLayout(skip: Bool) throws {
        let opened = try Self.open(Self.frontLayout, skip: skip)
        let tracks: [AVMediaType] = [AVMEDIA_TYPE_VIDEO, AVMEDIA_TYPE_SUBTITLE]
        #expect(opened.codecTypes == (skip ? tracks : tracks + [AVMEDIA_TYPE_ATTACHMENT, AVMEDIA_TYPE_ATTACHMENT]))
        #expect(opened.packets == 2)
    }

    @Test("attachments reached through the SeekHead are skipped, the tracks stay", arguments: [false, true])
    func seekHeadLayout(skip: Bool) throws {
        let opened = try Self.open(Self.seekHeadLayout, skip: skip)
        let tracks: [AVMediaType] = [AVMEDIA_TYPE_VIDEO, AVMEDIA_TYPE_SUBTITLE]
        #expect(opened.codecTypes == (skip ? tracks : tracks + [AVMEDIA_TYPE_ATTACHMENT]))
        #expect(opened.packets == 2)
    }

